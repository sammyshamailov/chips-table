// Entry point and composition root: creates everything, wires the effects to the table's events, then starts the
// app. No module does work when it is imported (CLAUDE.md rule 2); the first render happens in app.start().
import './styles/base.css';
import './styles/brand.css';
import './styles/room.css';
import './styles/sheet.css';
import './styles/blackjack.css';
import './styles/layout.css';
import './styles/rotate.css';
import './styles/end.css';
import { browserStorage } from './data/browser-storage';
import { createEventBus } from './sync/events';
import type { DomainEvent } from './sync/domain-events';
import { createSound } from './audio/synth';
import { createAmbiSync, startAudioControl } from './audio/control';
import { AMB_BED, AMB_LEVEL, AMB_MANIFEST, Ambience, loopBounds } from './audio/ambience';
import { VOICE_KEYS, VOICE_LEVEL, playLine, subscribeNarration, voiceUrl } from './audio/narration';
import { createFxLayer } from './fx/layer';
import { subscribeBlackjackFx } from './fx/blackjack';
import { subscribeHoldemFx } from './fx/holdem';
import { subscribeRoomFx } from './fx/room';
import { createUi } from './ui/app';
import { createApp, type App } from './app/app';

const storage = browserStorage();
const bus = createEventBus<DomainEvent>();
// The sound engine and the effects layer call back into the app only later (a touch, a timer, an event), never
// while they are being created, so `app` is set by then.
let app: App | null = null;
const theApp = () => app as App;
const inTable = () => theApp().inTable();
const snd = createSound({ storage, sync: () => ambiSync() });
const ambiSync = createAmbiSync(snd, inTable);
startAudioControl(snd, ambiSync, inTable);
const layer = createFxLayer({
  el: document.getElementById('fx') as HTMLElement,
  render: () => theApp().render(),
  myId: () => theApp().myId(),
});
// The screens (Preact components, src/ui/): mounted on the page's elements, drawn by the app's render().
const el = (id: string) => document.getElementById(id) as HTMLElement;
const ui = createUi({ app: el('app'), sheet: el('sheet'), toast: el('toast') });
app = createApp({ bus, snd, layer, storage, ambiSync, ui });

// The table's events → effects. The order matters where two react to one event: animations and their sounds
// first, the dealer's narration after (as it always ran). The ceremony is the app's own screen.
bus.on('GameEnded', { after: () => theApp().ceremony() });
subscribeBlackjackFx(bus, layer, snd);
subscribeHoldemFx(bus, layer, snd);
subscribeRoomFx(bus, layer, snd);
subscribeNarration(bus, key => snd.say(key));

// For tests/audio.js, which renders the background and the narration offline through the same code.
Object.assign(window, {
  ChipsAmbience: Ambience,
  ChipsLine: playLine,
  CHIPS_BG: {
    manifest: AMB_MANIFEST,
    level: AMB_LEVEL,
    bedLevel: AMB_BED,
    loopBounds,
    voiceKeys: VOICE_KEYS,
    voiceLevel: VOICE_LEVEL,
    voiceUrl,
  },
});

app.start();

// The service worker only exists in a build (dist/sw.js is generated by scripts/sw-plugin.mts).
if (import.meta.env.PROD && 'serviceWorker' in navigator)
  window.addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));
